import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {
  BUNDLED_FONT,
  FONT_PRESET,
  collectUiCharacters,
  fontAdd,
  fontOff,
  fontStatus,
  previewOverrides,
} from '../../core/font.mjs';

const TOOL_DIR = path.resolve(import.meta.dirname, '../..');

function fixture({ withTheme = true } = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'lvglui-font-'));
  const uiDir = path.join(root, 'components', 'app_ui');
  fs.mkdirSync(path.join(uiDir, 'src'), { recursive: true });
  fs.mkdirSync(path.join(uiDir, 'include'), { recursive: true });
  fs.writeFileSync(path.join(uiDir, 'screen.c'), `
#include "ui.h"
static void build(lv_obj_t *root) {
    lv_label_set_text(lv_label_create(root), "保存");
    lv_label_set_text(lv_label_create(root), "OK");
}
`, 'utf8');
  fs.writeFileSync(path.join(uiDir, 'CMakeLists.txt'), `idf_component_register(\n    SRCS "screen.c"\n    INCLUDE_DIRS "."\n)\n`, 'utf8');
  if (withTheme) {
    fs.writeFileSync(path.join(uiDir, 'src', 'ui_theme.c'), `
#include "lvgl.h"
void ui_theme_init(lv_obj_t *root)
{
    (void)root;
}
`, 'utf8');
  }
  return {
    root,
    uiDir,
    ctx: {
      ok: true,
      root,
      uiDir,
      toolDir: TOOL_DIR,
      config: { font: { mode: 'off', file: '', size: 16, name: '', cjk: false } },
    },
  };
}

test('collectUiCharacters keeps Chinese and printable ASCII', () => {
  const { uiDir } = fixture();
  const result = collectUiCharacters(uiDir);
  assert.ok(result.chars.includes('保'));
  assert.ok(result.chars.includes('存'));
  assert.ok(result.chars.includes('O'));
});

test('fontAdd writes a fake font, header, apply hook, theme, CMake and config', () => {
  const { root, uiDir, ctx } = fixture();
  const fake = (args) => {
    const output = args[args.indexOf('--output') + 1];
    fs.writeFileSync(output, '/* U+4FDD "保" */\n/* U+5B58 "存" */\nconst lv_font_t ui_font_noto_sc_16 = {0};\n', 'utf8');
    return { status: 0, stdout: '', stderr: '' };
  };
  const result = fontAdd(ctx, { preset: FONT_PRESET, size: 16, run: fake });
  assert.equal(result.ok, true);
  assert.equal(result.symbol, 'ui_font_noto_sc_16');
  assert.equal(result.chars, 97);
  assert.ok(!result.missing.includes('保'));
  assert.ok(!result.missing.includes('存'));

  const fontFile = path.join(uiDir, 'fonts', 'ui_font_noto_sc_16.c');
  assert.ok(fs.existsSync(fontFile));
  const header = fs.readFileSync(path.join(uiDir, 'include', 'ui_font.h'), 'utf8');
  assert.match(header, /LV_FONT_DECLARE\(ui_font_noto_sc_16\)/);
  assert.match(header, /void lvglui_apply_font\(lv_obj_t \*root\)/);
  const apply = fs.readFileSync(path.join(uiDir, 'src', 'ui_font_apply.c'), 'utf8');
  assert.match(apply, /Generated by lvglui font add/);
  assert.match(apply, /lv_obj_set_style_text_font\(root, &ui_font_noto_sc_16, 0\)/);
  const theme = fs.readFileSync(path.join(uiDir, 'src', 'ui_theme.c'), 'utf8');
  assert.match(theme, /lvglui:font:begin/);
  assert.match(theme, /#include "ui_font.h"/);
  const cmake = fs.readFileSync(path.join(uiDir, 'CMakeLists.txt'), 'utf8');
  assert.match(cmake, /"fonts\/ui_font_noto_sc_16\.c"/);
  assert.match(cmake, /"src\/ui_font_apply\.c"/);
  const config = JSON.parse(fs.readFileSync(path.join(root, 'lvglui.json'), 'utf8'));
  assert.equal(config.font.mode, 'project');
  assert.equal(config.font.name, 'ui_font_noto_sc_16');
  assert.equal(config.font.cjk, false);
});

test('fontAdd works without ui_theme.c and warns about the firmware hook', () => {
  const { uiDir, ctx } = fixture({ withTheme: false });
  const fake = (args) => {
    fs.writeFileSync(args[args.indexOf('--output') + 1], '/* U+4FDD */\n', 'utf8');
    return { status: 0 };
  };
  const result = fontAdd(ctx, { preset: FONT_PRESET, size: 16, run: fake });
  assert.equal(result.ok, true);
  assert.ok(result.warnings.some((w) => w.includes('ui_theme.c')));
  assert.ok(fs.existsSync(path.join(uiDir, 'src', 'ui_font_apply.c')));
});

test('fontAdd cleans files from a previous add and fontOff removes them all', () => {
  const { root, uiDir, ctx } = fixture();
  const fake = (args) => {
    fs.writeFileSync(args[args.indexOf('--output') + 1], '/* U+4FDD */\n', 'utf8');
    return { status: 0 };
  };
  assert.equal(fontAdd(ctx, { preset: FONT_PRESET, size: 16, run: fake }).ok, true);
  const old = path.join(uiDir, 'fonts', 'ui_font_noto_sc_16.c');
  assert.ok(fs.existsSync(old));

  const second = fontAdd(ctx, { preset: FONT_PRESET, size: 18, name: 'ui_font_noto_sc_18', run: fake });
  assert.equal(second.ok, true);
  assert.equal(fs.existsSync(old), false);
  assert.ok(fs.existsSync(path.join(uiDir, 'fonts', 'ui_font_noto_sc_18.c')));
  const cmake = fs.readFileSync(path.join(uiDir, 'CMakeLists.txt'), 'utf8');
  assert.doesNotMatch(cmake, /ui_font_noto_sc_16/);
  assert.match(cmake, /ui_font_noto_sc_18/);

  const off = fontOff(ctx);
  assert.equal(off.ok, true);
  assert.equal(fs.existsSync(path.join(uiDir, 'fonts', 'ui_font_noto_sc_18.c')), false);
  assert.equal(fs.existsSync(path.join(uiDir, 'include', 'ui_font.h')), false);
  assert.equal(fs.existsSync(path.join(uiDir, 'src', 'ui_font_apply.c')), false);
  assert.doesNotMatch(fs.readFileSync(path.join(uiDir, 'CMakeLists.txt'), 'utf8'), /ui_font_/);
  assert.doesNotMatch(fs.readFileSync(path.join(uiDir, 'src', 'ui_theme.c'), 'utf8'), /lvglui:font/);
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'lvglui.json'), 'utf8')).font.mode, 'off');
});

test('real conversion of the bundled Noto Sans SC is uncompressed and contains Chinese', () => {
  const { uiDir, ctx } = fixture();
  const result = fontAdd(ctx, { preset: FONT_PRESET, size: 16, chars: '保存' });
  assert.equal(result.ok, true, JSON.stringify(result.problems));
  assert.equal(result.missing.length, 0);
  const c = fs.readFileSync(path.join(uiDir, 'fonts', 'ui_font_noto_sc_16.c'), 'utf8');
  assert.match(c, /bitmap_format = 0/);
  assert.match(c, /U\+4FDD "保"/);
  assert.match(c, /U\+5B58 "存"/);
  assert.ok(fs.statSync(path.join(TOOL_DIR, BUNDLED_FONT)).size > 0);
});

test('fontStatus reports missing non-ASCII characters when off and project mode after add', () => {
  const { uiDir, ctx } = fixture();
  const off = fontStatus(ctx);
  assert.equal(off.mode, 'off');
  assert.ok(off.missing.some((ch) => ch === '保'));

  const fake = (args) => {
    fs.writeFileSync(args[args.indexOf('--output') + 1], '/* U+4FDD "保" */\n/* U+5B58 "存" */\n', 'utf8');
    return { status: 0 };
  };
  const add = fontAdd(ctx, { preset: FONT_PRESET, size: 16, run: fake });
  assert.equal(add.ok, true);
  const status = fontStatus({ ...ctx, config: add.config });
  assert.equal(status.mode, 'project');
  assert.ok(!status.missing.includes('保'));
});

test('previewOverrides only keeps built-in CJK fonts in cjk mode', () => {
  const cjkKeys = (overrides) => Object.keys(overrides).filter((k) => k.startsWith('LV_FONT_SOURCE_HAN_SANS_SC_'));
  assert.equal(cjkKeys(previewOverrides({ font: { mode: 'cjk' } })).length, 2);
  assert.equal(cjkKeys(previewOverrides({ font: { mode: 'off' } })).length, 0);
  assert.equal(cjkKeys(previewOverrides({ font: { mode: 'project' } })).length, 0);
});