test('fontAdd cleans files from a previous add and fontOff removes them all', () => {
  const { root, uiDir, ctx } = fixture();
  const fake = (args) => {
    fs.writeFileSync(args[args.indexOf('--output') + 1], '/* U+4FDD */\n', 'utf8');
    return { status: 0 };
  };
  assert.equal(fontAdd(ctx, { preset: FONT_PRESET, size: 16, run: fake }).ok, true);
  const old = path.join(uiDir, 'fonts', 'ui_font_noto_sc_16.c');
  assert.ok(fs.existsSync(old));

  const second = fontAdd(ctx, { preset: FONT_PRESET, size: 18, name: 'ui_font_noto_sc_18', run: fake });
  assert.equal(second.ok, true);
  assert.equal(fs.existsSync(old), false);
  assert.ok(fs.existsSync(path.join(uiDir, 'fonts', 'ui_font_noto_sc_18.c')));
  const cmake = fs.readFileSync(path.join(uiDir, 'CMakeLists.txt'), 'utf8');
  assert.doesNotMatch(cmake, /ui_font_noto_sc_16/);
  assert.match(cmake, /ui_font_noto_sc_18/);

  const off = fontOff(ctx);
  assert.equal(off.ok, true);
  assert.equal(fs.existsSync(path.join(uiDir, 'fonts', 'ui_font_noto_sc_18.c')), false);
  assert.equal(fs.existsSync(path.join(uiDir, 'fonts')), false);
  assert.equal(fs.existsSync(path.join(uiDir, 'include', 'ui_font.h')), false);
  assert.equal(fs.existsSync(path.join(uiDir, 'src', 'ui_font_apply.c')), false);
  assert.doesNotMatch(fs.readFileSync(path.join(uiDir, 'CMakeLists.txt'), 'utf8'), /ui_font_/);
  assert.doesNotMatch(fs.readFileSync(path.join(uiDir, 'src', 'ui_theme.c'), 'utf8'), /lvglui:font/);
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'lvglui.json'), 'utf8')).font.mode, 'off');
});

